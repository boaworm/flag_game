/**
 * The playable sets.
 *
 * A set is a group of places that share a map and a way of being divided up —
 * countries of the world grouped by continent, or US states grouped by region.
 * Modes are written against this shape and never against countries specifically,
 * so a new set is a build script and an entry here.
 *
 * Not every set can feed every mode. A set says what it has and a mode says what
 * it needs, and the two are matched when a game is set up:
 *
 *   flags     a flag for each place, so a flag can be shown or picked
 *   outlines  shapes distinctive enough to recognise, so one can be placed
 *
 * Ancient Greece has neither. Its city states have no settled banner, and most
 * of its places are sites rather than territories — Knossos is a palace, and its
 * outline is a circle drawn round a point, which would make a nonsense of a mode
 * that asks the player to recognise a shape.
 *
 * Each set's data is generated by the matching tool and committed under
 * data/sets/<id>/. Nothing in the game hardcodes a place name or code.
 */

