/** Can this set feed this mode? */
export const setSuits = (set, mode) =>
  (mode.needs ?? []).every((need) => Boolean(set[need]));

export const setById = (id) => SETS.find((s) => s.id === id) ?? SETS[0];

const cache = new Map();

async function loadJson(path) {
  const response = await fetch(path);
  if (!response.ok) throw new Error(`Could not load ${path} (HTTP ${response.status})`);
  return response.json();
}

/** A set's places. Loaded once per set. */
export async function loadEntries(set) {
  const key = `${set.id}:entries`;
  if (!cache.has(key)) cache.set(key, await loadJson(`data/sets/${set.id}/entries.json`));
  return cache.get(key);
}

/** A set's geometry. Only the map modes ask for it, and only once. */
export async function loadMap(set) {
  const key = `${set.id}:map`;
  if (!cache.has(key)) cache.set(key, await loadJson(`data/sets/${set.id}/map.json`));
  return cache.get(key);
}

/** Is this set worth narrowing down, or is it one map's worth as it stands? */
export const isDivided = (set) => Boolean(set.groupLabel);

/** The groups a set can be narrowed to, in a stable order, 'All' first. */
export const groupsOf = (entries) => [
  'All',
  ...[...new Set(entries.map((e) => e.group))].sort(),
];

/** Entries in a group, or all of them. */
export const inGroup = (entries, group) =>
  group === 'All' ? entries : entries.filter((e) => e.group === group);

/** Path to a place's flag, or null for a set that has none. */
export const flagUrl = (set, entry) => (set.flags ? `${set.flags}/${entry.code}.svg` : null);
